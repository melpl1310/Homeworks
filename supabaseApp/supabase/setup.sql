begin;

create table if not exists public.tareas (
  id bigint generated by default as identity primary key,
  titulo text not null,
  completada boolean not null default false,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

do $$
begin
  if exists (
    select 1
    from public.tareas
    group by user_id, lower(btrim(titulo))
    having count(*) > 1
  ) then
    raise exception 'Hay títulos de tareas duplicados por usuario. Elimínalos o renómbralos antes de ejecutar esta configuración.';
  end if;
end
$$;

create unique index if not exists tareas_usuario_titulo_unico
  on public.tareas (user_id, lower(btrim(titulo)));

alter table public.tareas enable row level security;

drop policy if exists tareas_select_own on public.tareas;
create policy tareas_select_own
  on public.tareas for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists tareas_insert_own on public.tareas;
create policy tareas_insert_own
  on public.tareas for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists tareas_update_own on public.tareas;
create policy tareas_update_own
  on public.tareas for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists tareas_delete_own on public.tareas;
create policy tareas_delete_own
  on public.tareas for delete to authenticated
  using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.tareas to authenticated;

do $$
declare
  identity_sequence regclass;
begin
  identity_sequence := pg_get_serial_sequence('public.tareas', 'id');
  if identity_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to authenticated',
      identity_sequence
    );
  end if;
end
$$;

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'avatars',
  'avatars',
  false,
  2097152,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update
set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists avatars_select_own on storage.objects;
create policy avatars_select_own
  on storage.objects for select to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists avatars_insert_own on storage.objects;
create policy avatars_insert_own
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists avatars_update_own on storage.objects;
create policy avatars_update_own
  on storage.objects for update to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists avatars_delete_own on storage.objects;
create policy avatars_delete_own
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

do $$
begin
  if not exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    raise exception 'No existe la publicación supabase_realtime en este proyecto.';
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'tareas'
  ) then
    alter publication supabase_realtime add table public.tareas;
  end if;
end
$$;

commit;
